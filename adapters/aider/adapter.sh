#!/usr/bin/env bash
set -euo pipefail
# ============================================================
# Aider adapter — runtime functions only
# ============================================================
#
# Config assembly is handled by `keel compile`. This adapter
# provides runtime-only hooks: backend configuration, onboarding,
# status display, and launch functions.
#
# Adapter interface (7 functions):
#   adapter_configure_backend
#   adapter_write_onboarding
#   adapter_print_backend_status
#   adapter_print_warnings
#   adapter_launch
#   adapter_launch_tmux
#   adapter_launch_headless
# ============================================================

# Source lib utilities
source /usr/local/lib/config.sh
source /usr/local/lib/git.sh
source /usr/local/lib/launch.sh
source /usr/local/lib/status.sh

TOOL_NAME="Aider"
TOOL_COMMAND="aider"
TOOL_HOME_DIR=".aider"
TOOL_SESSION_NAME="aider"
TOOL_HOME="${HOME}/${TOOL_HOME_DIR}"

# ============================================================
# Backend configuration (multi-provider)
# ============================================================

adapter_configure_backend() {
    _AIDER_PROVIDERS=""
    _AIDER_AUTH_MISSING=1

    if [ -n "${OPENAI_API_KEY:-}" ]; then
        _AIDER_PROVIDERS="${_AIDER_PROVIDERS}OpenAI "
        _AIDER_AUTH_MISSING=0
    fi
    if [ -n "${ANTHROPIC_API_KEY:-}" ]; then
        _AIDER_PROVIDERS="${_AIDER_PROVIDERS}Anthropic "
        _AIDER_AUTH_MISSING=0
    fi
    if [ -n "${DEEPSEEK_API_KEY:-}" ]; then
        _AIDER_PROVIDERS="${_AIDER_PROVIDERS}DeepSeek "
        _AIDER_AUTH_MISSING=0
    fi
    if [ -n "${OPENROUTER_API_KEY:-}" ]; then
        _AIDER_PROVIDERS="${_AIDER_PROVIDERS}OpenRouter "
        _AIDER_AUTH_MISSING=0
    fi
    if [ -n "${GEMINI_API_KEY:-}" ] || [ -n "${GOOGLE_API_KEY:-}" ]; then
        _AIDER_PROVIDERS="${_AIDER_PROVIDERS}Gemini "
        _AIDER_AUTH_MISSING=0
    fi

    # Google Vertex AI
    local cred_file="${GOOGLE_APPLICATION_CREDENTIALS:-/secrets/gcp-sa.json}"
    if [ -n "${GOOGLE_VERTEX_PROJECT:-}" ] || [ -f "${cred_file}" ]; then
        _AIDER_PROVIDERS="${_AIDER_PROVIDERS}Vertex "
        _AIDER_AUTH_MISSING=0
    fi

    # Local models (Ollama, LM Studio, etc.)
    if [ -n "${OLLAMA_HOST:-}" ] || [ -n "${OLLAMA_API_BASE:-}" ]; then
        _AIDER_PROVIDERS="${_AIDER_PROVIDERS}Ollama "
        _AIDER_AUTH_MISSING=0
    fi
}

# ============================================================
# First-run onboarding bypass
# ============================================================

adapter_write_onboarding() {
    # Aider does not require explicit onboarding bypass.
    # Configuration is driven by .env files and environment variables.
    # Create .aider directory to prevent first-run directory creation prompt
    mkdir -p "${TOOL_HOME}"

    # Create minimal .aider.conf.yml if needed
    local config_file="${HOME}/.aider.conf.yml"
    if [ ! -f "${config_file}" ]; then
        cat > "${config_file}" <<EOF
# Aider configuration (auto-generated by Keel)
auto-commits: true
dirty-commits: true
EOF
    fi
}

# ============================================================
# Status display hooks
# ============================================================

adapter_print_backend_status() {
    keel_status_kv "Backend" "Aider"
    if [ -n "${_AIDER_PROVIDERS}" ]; then
        keel_status_kv "Providers" "${_AIDER_PROVIDERS% }"
    else
        keel_status_kv "Providers" "none configured"
    fi
    keel_status_kv "Model" "${AIDER_MODEL:-auto-detect}"
}

adapter_print_warnings() {
    if [ "${_AIDER_AUTH_MISSING:-1}" -eq 1 ]; then
        echo "WARNING: No AI provider configured. Aider requires at least one."
        echo "  Set one or more: OPENAI_API_KEY, ANTHROPIC_API_KEY, DEEPSEEK_API_KEY"
        echo "  Or for other providers: OPENROUTER_API_KEY, GEMINI_API_KEY"
        echo "  Or for Vertex: GOOGLE_VERTEX_PROJECT + credentials mount"
        echo "  Or for local: OLLAMA_HOST or OLLAMA_API_BASE"
        echo ""
    fi
}

# ============================================================
# Launch functions
# ============================================================

adapter_launch() {
    exec "${TOOL_COMMAND}" "$@"
}

adapter_launch_tmux() {
    keel_launch_tmux "${TOOL_SESSION_NAME}" "${TOOL_COMMAND}" "$@"
}

adapter_launch_headless() {
    # SECURITY: PROMPT is constructed from user-controlled CMD args ($@) and
    # passed verbatim to the agent CLI via --message. This is a prompt injection
    # surface — the agent CLI is the trust boundary, not this script.
    local PROMPT="${*:-Review this codebase.}"

    local MODEL="${AIDER_MODEL:-}"
    local OUTPUT_FORMAT="${OUTPUT_FORMAT:-}"

    echo "--- ${TOOL_NAME} Runner ---"
    echo "Prompt:  ${PROMPT}"
    adapter_print_backend_status
    echo "----------------------"

    local ARGS=(
        "--message" "${PROMPT}"
        "--yes-always"
        "--no-show-release-notes"
    )

    if [ -n "${MODEL}" ]; then
        ARGS+=("--model" "${MODEL}")
    fi

    # Add output format if specified (aider supports --output for structured output)
    if [ -n "${OUTPUT_FORMAT}" ]; then
        ARGS+=("--output" "${OUTPUT_FORMAT}")
    fi

    # Auto-commit changes (headless mode should commit)
    ARGS+=("--auto-commits")

    exec "${TOOL_COMMAND}" "${ARGS[@]}"
}
