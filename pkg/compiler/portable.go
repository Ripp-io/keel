package compiler

import (
	"encoding/json"

	"gitlab.com/ripp.io/oss/agentic/keel/pkg/schema"
)

// normalizeAttribution extracts attribution from an agent-specific settings
// map and returns a CanonicalAttribution. Returns nil if no attribution found.
// Handles both Claude format (template strings) and Cursor format (booleans).
// Deletes the "attribution" key from the map if found.
func normalizeAttribution(agentSettings map[string]any) *CanonicalAttribution {
	attrRaw, ok := agentSettings["attribution"]
	if !ok {
		return nil
	}
	attrMap, ok := attrRaw.(map[string]any)
	if !ok {
		return nil
	}
	delete(agentSettings, "attribution")

	attr := &CanonicalAttribution{}

	// Claude format: {"commit": "Co-Authored-By: ...", "pr": "Generated by ..."}
	if commit, ok := attrMap["commit"].(string); ok && commit != "" {
		attr.CommitEnabled = true
		attr.CommitTemplate = commit
	}
	if pr, ok := attrMap["pr"].(string); ok && pr != "" {
		attr.PREnabled = true
		attr.PRTemplate = pr
	}

	// Cursor format: {"attributeCommitsToAgent": true, "attributePRsToAgent": true}
	if commitEnabled, ok := attrMap["attributeCommitsToAgent"].(bool); ok {
		attr.CommitEnabled = commitEnabled
	}
	if prEnabled, ok := attrMap["attributePRsToAgent"].(bool); ok {
		attr.PREnabled = prEnabled
	}

	return attr
}

// normalizeSandbox extracts sandbox config from an agent-specific settings
// map and returns a canonical SandboxConfig. Returns nil if no sandbox found.
// Handles Claude format (embedded in settings.json with camelCase keys).
// Deletes the "sandbox" key from the map if found.
func normalizeSandbox(agentSettings map[string]any) *schema.SandboxConfig {
	sbRaw, ok := agentSettings["sandbox"]
	if !ok {
		return nil
	}
	sbMap, ok := sbRaw.(map[string]any)
	if !ok {
		return nil
	}
	delete(agentSettings, "sandbox")

	// Round-trip through JSON to populate the typed struct.
	// The SandboxConfig json tags match Claude's camelCase format.
	data, err := json.Marshal(sbMap)
	if err != nil {
		return nil
	}
	var sb schema.SandboxConfig
	if err := json.Unmarshal(data, &sb); err != nil {
		return nil
	}
	return &sb
}

// ExtractPortableConcepts extracts attribution and sandbox from an agent's
// settings map into the IR's canonical fields. Call this after settings
// have been classified into AgentSpecific — it promotes portable concepts
// from agent-specific to the canonical IR representation.
func ExtractPortableConcepts(ir *LayerIR, agent string) {
	if ir.AgentSpecific == nil || ir.AgentSpecific[agent] == nil {
		return
	}
	agentSettings := ir.AgentSpecific[agent]

	if attr := normalizeAttribution(agentSettings); attr != nil {
		ir.Attribution = attr
	}
	if sb := normalizeSandbox(agentSettings); sb != nil {
		ir.Sandbox = sb
	}
}
