// Package agentplugins provides the Agent Plugins 1.0 adapter for the Keel compiler.
// Agent Plugins is the cross-agent plugin packaging standard (agent-plugins.org)
// backed by Vercel, AWS, Microsoft, OpenAI, and Google. A plugin is a directory
// containing plugin.json (manifest), skills/ (Agent Skills), and mcp.json
// (MCP server config). Keel compiles layers into this format so plugins can be
// consumed by any supporting agent (ChatGPT, Codex, Cursor, Copilot, Kiro, VS Code).
package agentplugins

import (
	"gitlab.com/ripp.io/oss/agentic/keel/pkg/compiler"
	"gitlab.com/ripp.io/oss/agentic/keel/pkg/config"
)

func init() {
	config.RegisterAgent(config.AgentMeta{
		Format: "agentplugins",
		Files:  []string{"plugin.json"},
		Dirs:   []string{".agentplugins"},
	})
	compiler.RegisterCompiler("agentplugins", Compile)
	compiler.RegisterReader("agentplugins", func() compiler.NativeReader {
		return &Reader{}
	})
	compiler.RegisterProfileFunc("agentplugins", func(compiler.Scope) compiler.AgentProfile {
		return ProjectProfile()
	})
}

// Compile produces Agent Plugins 1.0 output:
//
//	plugin.json   manifest (name, version, description, metadata)
//	skills/       Agent Skills (SKILL.md standard)
//	mcp.json      MCP server config with typed transports
func Compile(layers []config.Layer, outputDir string, opts compiler.CompileOptions) (*compiler.CompileResult, error) {
	return compiler.CompileWithProfile(ProjectProfile(), layers, outputDir, opts)
}

// ProjectProfile returns the AgentProfile for Agent Plugins 1.0.
// Agent Plugins is a packaging format, not an agent config format.
// It supports skills and MCP only — no instructions, hooks, permissions,
// commands, agents, or settings in the traditional sense.
func ProjectProfile() compiler.AgentProfile {
	return compiler.AgentProfile{
		Name:       "agentplugins",
		OutputRoot: ".agentplugins",

		// No instruction file — plugins provide skills and MCP, not instructions.
		InstructionOutput:       "",
		SharedInstructionOutput: "",
		InstructionShimTemplate: "",

		// No settings file — plugin.json is generated by the custom writer.
		SettingsFile: "",
		SettingsLockKey: "",

		// No MCP output path — mcp.json is generated by the custom writer
		// with Agent Plugins-specific schema and typed transports.
		MCPOutput: "",

		HooksInSettings: false,

		// Skills are the primary content. Written to outputDir/skills/ by the
		// custom writer (not under .agentplugins/).
		Categories: []compiler.CategoryDef{
			{DirName: "skills", LockCategory: "skill"},
		},

		InstructionCandidates: []string{"plugin.json"},
		SettingsCandidates:    nil,

		HookKeyTransform:  compiler.IdentityTransform(),
		ToolNameTransform: compiler.IdentityTransform(),

		Capabilities: compiler.Capabilities{
			Skills: true,
			MCP:    true,
			// Everything else is false — plugins don't support these features.
		},
	}
}
